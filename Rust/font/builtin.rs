fn accented(base: u8, accent: u8, shift: bool) -> [u8; 8] {
    let source = ASCII[(base - 0x20) as usize];
    let mut out = [0; 8];
    out[0] = accent;
    for row in 1..8 {
        out[row] = source[if shift { row - 1 } else { row }];
    }
    out
}
fn cedilla(base: u8) -> [u8; 8] {
    let mut out = ASCII[(base - 0x20) as usize];
    out[7] = 0x30;
    out
}
pub fn row_mask(cp: u32, row: u32) -> u64 {
    if row >= 8 {
        return 0;
    }
    let source = glyph(cp)[row as usize];
    let mut out = 0;
    for column in 0..8 {
        if (source >> (7 - column)) & 1 == 1 {
            out |= 1u64 << column;
        }
    }
    out
}
